// 二叉树类定义头文件
//
// BinTree 类（基于链式存储的二叉树）:
//   构造/析构:
//     BinTree();                 // 构造函数，创建空二叉树
//     ~BinTree();                // 析构函数，释放所有结点
//   创建:
//     BinTreeNode* CreateByPreOrder();  // 从前序输入（-1 表示空）创建二叉树
//   遍历:
//     void PreOrder();           // 递归前序遍历
//     void InOrder();            // 递归中序遍历
//     void PostOrder();          // 递归后序遍历
//     void LevelOrder();         // 层次遍历（借助队列）
//   统计:
//     int NodeCount();           // 统计结点总数
//     int LeafCount();           // 统计叶子结点数
//     int Height();              // 计算二叉树高度
//   查找:
//     BinTreeNode* Search(int val); // 按值查找第一个匹配结点
//   其他:
//     void Mirror();             // 镜像翻转（左右子树互换）
//     bool IsEmpty();            // 判断是否为空
//
// 注：内部递归辅助函数以私有方式封装，不对外暴露
// 创建日期: 2024-1-1
// Author: Cyber Kaka
//****************************************************************************

#ifndef BINTREE_H
#define BINTREE_H

#include <iostream>
#include "BinTreeNode.h"
using namespace std;

class BinTree
{
public:
	BinTree();							//构造函数，创建空二叉树（m_pRoot = NULL）
	~BinTree();							//析构函数，递归释放所有结点

	/****** 创建 ******/

	/****************************************************************/
	/* BinTreeNode* CreateByPreOrder()								*/
	/* 功能:从标准输入按前序读入数据，以 -1 表示空结点，创建二叉树	*/
	/*   输入格式示例（前序）: 1 2 4 -1 -1 5 -1 -1 3 -1 -1			*/
	/*   对应结构:	   1							*/
	/*			      / \							*/
	/*			     2   3							*/
	/*			    / \								*/
	/*			   4   5							*/
	/* 返回值: 创建好的二叉树根节点指针								*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	BinTreeNode* CreateByPreOrder();

	/****** 遍历 ******/

	/****************************************************************/
	/* void PreOrder()												*/
	/* 功能:前序遍历（根-左-右），递归实现							*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	void PreOrder();

	/****************************************************************/
	/* void InOrder()												*/
	/* 功能:中序遍历（左-根-右），递归实现							*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	void InOrder();

	/****************************************************************/
	/* void PostOrder()												*/
	/* 功能:后序遍历（左-右-根），递归实现							*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	void PostOrder();

	/****************************************************************/
	/* void LevelOrder()											*/
	/* 功能:层次遍历（广度优先），借助队列实现						*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	void LevelOrder();

	/****** 统计 ******/

	/****************************************************************/
	/* int NodeCount()												*/
	/* 功能:统计二叉树中所有结点的总数								*/
	/* 返回值: 结点总数												*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	int NodeCount();

	/****************************************************************/
	/* int LeafCount()												*/
	/* 功能:统计叶子结点（左右孩子均为空的结点）的数目				*/
	/* 返回值: 叶子结点数											*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	int LeafCount();

	/****************************************************************/
	/* int Height()													*/
	/* 功能:计算二叉树的高度（根节点深度为1）						*/
	/* 返回值: 树高（空树返回0）									*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	int Height();

	/****** 查找 ******/

	/****************************************************************/
	/* BinTreeNode* Search(int val)									*/
	/* 功能:前序遍历查找第一个数据域等于 val 的结点					*/
	/* 输入参数 val: 待查找的值									*/
	/* 返回值: 找到则返回该结点指针，否则返回 NULL					*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	BinTreeNode* Search(int val);

	/****** 其他操作 ******/

	/****************************************************************/
	/* void Mirror()												*/
	/* 功能:将二叉树镜像翻转（所有结点的左右子树互换）				*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	void Mirror();

	/****************************************************************/
	/* bool IsEmpty()												*/
	/* 功能:判断二叉树是否为空树									*/
	/* 返回值: 空树返回 true，否则返回 false						*/
	/* 创建日期: 2024-1-1					Author:Cyber Kaka		*/
	/****************************************************************/
	bool IsEmpty();

	BinTreeNode *m_pRoot;				//根节点指针（public，方便演示赋值）

private:
	//---- 以下为内部递归辅助函数 ----

	// 递归释放以 pNode 为根的子树所有结点
	void destroyTree(BinTreeNode *pNode);

	// 从前序输入递归创建二叉树，返回创建好的子树根节点
	BinTreeNode* createHelper();

	// 递归前序遍历
	void preOrderHelper(BinTreeNode *pNode);

	// 递归中序遍历
	void inOrderHelper(BinTreeNode *pNode);

	// 递归后序遍历
	void postOrderHelper(BinTreeNode *pNode);

	// 递归统计结点数
	int nodeCountHelper(BinTreeNode *pNode);

	// 递归统计叶子数
	int leafCountHelper(BinTreeNode *pNode);

	// 递归计算树高
	int heightHelper(BinTreeNode *pNode);

	// 递归查找结点
	BinTreeNode* searchHelper(BinTreeNode *pNode, int val);

	// 递归镜像翻转
	void mirrorHelper(BinTreeNode *pNode);
};

#endif // BINTREE_H
