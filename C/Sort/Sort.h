// 排序算法合集头文件
// 包含常见的六种内部排序算法：冒泡、插入、选择、希尔、归并、快排、堆排
// 时间复杂度对比：
//   冒泡排序:  O(n^2)        稳定
//   插入排序:  O(n^2)        稳定
//   选择排序:  O(n^2)        不稳定
//   希尔排序:  O(n^1.3)~O(n^2) 不稳定（依赖增量序列）
//   归并排序:  O(n log n)    稳定
//   快速排序:  O(n log n)均  不稳定
//   堆排序:    O(n log n)    不稳定

#ifndef SORT_H
#define SORT_H

#include <stdio.h>
#include <stdlib.h>

/****************************************************************/
/* void printArray(int arr[], int n)							*/
/* 功能:打印整型数组，用于排序结果展示							*/
/* 输入参数 arr: 待打印数组										*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void printArray(int arr[], int n);

/****************************************************************/
/* void bubbleSort(int arr[], int n)							*/
/* 功能:冒泡排序												*/
/*   思路:每轮将最大元素"冒泡"到末尾，共 n-1 轮				*/
/*   时间复杂度: O(n^2)（最坏/平均），O(n)（最好，已有序）	*/
/*   空间复杂度: O(1)　　稳定排序								*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void bubbleSort(int arr[], int n);

/****************************************************************/
/* void insertionSort(int arr[], int n)							*/
/* 功能:直接插入排序											*/
/*   思路:将每个元素插入到前面已排好序的子序列中的合适位置		*/
/*   时间复杂度: O(n^2)（最坏/平均），O(n)（最好，已有序）	*/
/*   空间复杂度: O(1)　　稳定排序								*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void insertionSort(int arr[], int n);

/****************************************************************/
/* void selectionSort(int arr[], int n)							*/
/* 功能:简单选择排序											*/
/*   思路:每轮从未排序部分中选出最小值，交换到当前位置			*/
/*   时间复杂度: O(n^2)（所有情况）							*/
/*   空间复杂度: O(1)　　不稳定排序							*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void selectionSort(int arr[], int n);

/****************************************************************/
/* void shellSort(int arr[], int n)								*/
/* 功能:希尔排序（缩小增量排序）								*/
/*   思路:以递减增量分组，对每组进行插入排序					*/
/*   时间复杂度: 依赖增量序列，通常约 O(n^1.3)				*/
/*   空间复杂度: O(1)　　不稳定排序							*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void shellSort(int arr[], int n);

/****************************************************************/
/* void mergeSort(int arr[], int n)								*/
/* 功能:归并排序（递归版）										*/
/*   思路:将数组二分后分别排序，再将两个有序子数组合并		*/
/*   时间复杂度: O(n log n)（所有情况）						*/
/*   空间复杂度: O(n)（需额外辅助空间）　稳定排序			*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void mergeSort(int arr[], int n);

/****************************************************************/
/* void quickSort(int arr[], int low, int high)					*/
/* 功能:快速排序（递归版，Lomuto 划分方案）					*/
/*   思路:选取基准 pivot，将数组划分为小于/大于两部分，递归	*/
/*   时间复杂度: O(n log n) 平均，O(n^2) 最坏（已有序）		*/
/*   空间复杂度: O(log n) 平均（递归栈）　不稳定排序			*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 low: 排序起始下标									*/
/* 输入参数 high: 排序终止下标									*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void quickSort(int arr[], int low, int high);

/****************************************************************/
/* void heapSort(int arr[], int n)								*/
/* 功能:堆排序（大顶堆）										*/
/*   思路:先建大顶堆，然后每次将堆顶与末尾交换并重新堆化		*/
/*   时间复杂度: O(n log n)（所有情况）						*/
/*   空间复杂度: O(1)（原地排序）　不稳定排序				*/
/* 输入参数 arr: 输入输出数组									*/
/* 输入参数 n: 数组长度											*/
/* 返回值: 无													*/
/* 创建日期: 2024-1-1						Author:Cyber Kaka	*/
/****************************************************************/
void heapSort(int arr[], int n);

#endif	// SORT_H
